-- ── 4 · Servicios Prestados ────────────────────────────────────────────────
CREATE TABLE ai.act_servicio_prestado (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad        bigint NOT NULL REFERENCES ai.actividad(id) ON DELETE CASCADE,
  id_servicio_prestado smallint NOT NULL REFERENCES ref.servicio_prestado(id),
  cantidad            integer NOT NULL,
  observacion         text,
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          bigint,
  modificado_en       timestamptz NOT NULL DEFAULT now(),
  modificado_por      bigint,
  -- Las cantidades alimentan el RAO y llegan a rendiciones de cuentas. Cero es
  -- un dato ambiguo («no hubo» o «no se conto»), asi que se exige positivo: si
  -- no hubo servicio, no se registra la fila.
  CONSTRAINT act_servicio_prestado_cantidad_positiva CHECK (cantidad > 0),
  CONSTRAINT act_servicio_prestado_unico UNIQUE (id_actividad, id_servicio_prestado)
);
