-- ═══════════════════════════════════════════════════════════════════════════
-- 0007 — Las once tablas hijas de una actividad (R19)
--
-- ⚠️ ESTE ARCHIVO ES LA RESPUESTA AL ANTI-PATRON P2.
--
-- El diseno auditado «declaraba nueve tablas hijas y su DDL creaba cuatro;
-- faltaba `act_poblacion_beneficiada`, la cifra que alimenta el RAO». Aqui
-- estan las ONCE, y el test de inventario de la Puerta 1 falla si falta
-- alguna, citandola por su nombre.
--
-- Orden y nombres tal como los enumera R19:
--    1 Tipo Operacion          -> ai.act_tipo_operacion
--    2 Archivos Adjuntos       -> ai.act_adjunto
--    3 Entidades Servicios     -> ai.act_entidad_servicio
--    4 Servicios Prestados     -> ai.act_servicio_prestado
--    5 Poblacion Beneficiada   -> ai.act_poblacion_beneficiada   ← la que se perdio
--    6 Entidades Apoyadas      -> ai.act_entidad_apoyada
--    7 Medios Difusion         -> ai.act_medio_difusion
--    8 Medios Utilizados       -> ai.act_medio_utilizado
--    9 Recursos Utilizados     -> ai.act_recurso_utilizado
--   10 Bienes Donados          -> ai.act_bien_donado
--   11 Resumen                 -> ai.act_resumen
--
-- La obligatoriedad de las once NO se expresa con NOT NULL: son tablas hijas
-- que pueden quedar vacias. Se calcula en `ai.actividad.registro_completo`
-- (disparador de 0009) y los consolidados del RAO filtran por el.
--
-- ⚠️ TODO(JACID) Q4: de cinco de estas pestanas no se conocen los campos
-- reales (Tipo Operacion, Entidades Servicios, Servicios Prestados, Poblacion
-- Beneficiada, Entidades Apoyadas). Los campos de abajo son los minimos que
-- las reglas permiten afirmar. NO se han inventado campos verosimiles: un
-- campo inventado que nadie llena es ruido, y uno que alguien llena con otro
-- significado es un dato falso.
-- ═══════════════════════════════════════════════════════════════════════════

