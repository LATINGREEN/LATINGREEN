-- ── 2 · Archivos Adjuntos ──────────────────────────────────────────────────
--
-- R11 (cuota de 10 MB AGREGADA) y R12 (extensiones y MIME real).
--
-- El binario va a MinIO; aqui quedan ruta, metadatos y hash_sha256.
CREATE TABLE ai.act_adjunto (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad         bigint NOT NULL REFERENCES ai.actividad(id) ON DELETE CASCADE,
  nombre_archivo       varchar(255) NOT NULL,
  extension            varchar(10) NOT NULL REFERENCES ref.extension_permitida(extension),
  id_categoria_adjunto smallint NOT NULL REFERENCES ref.categoria_adjunto(id),
  -- R12: el MIME que el analisis del CONTENIDO REAL devolvio, no el que
  -- declaro el navegador. Se guarda para poder auditar despues por que se
  -- acepto un archivo.
  mime_detectado       varchar(120) NOT NULL,
  peso_bytes           bigint NOT NULL,
  hash_sha256          char(64) NOT NULL,
  ruta_objeto          varchar(500) NOT NULL,
  id_fase_documental   smallint NOT NULL REFERENCES ref.fase_documental(id),

  -- R14: borrado logico. Importa para R11: la cuota suma los bytes VIGENTES,
  -- asi que un adjunto dado de baja libera su espacio sin desaparecer.
  id_estado_registro   smallint NOT NULL REFERENCES ref.estado_registro(id),

  creado_en            timestamptz NOT NULL DEFAULT now(),
  creado_por           bigint,
  modificado_en        timestamptz NOT NULL DEFAULT now(),
  modificado_por       bigint,

  -- ⚠️ NO existe aqui un `CHECK (peso_bytes <= 10485760)`. Eso es exactamente
  -- el anti-patron P5: limitaria cada archivo, no la suma, y cuarenta archivos
  -- de 9 MB pasarian. La cuota AGREGADA la impone el disparador
  -- `ai.verificar_cuota_adjuntos` de la migracion 0009.
  --
  -- Lo que si tiene sentido comprobar por fila: que el archivo no este vacio y
  -- que un solo archivo no supere ya la cuota completa, porque en ese caso no
  -- hay forma de que quepa y el disparador lo rechazaria igual.
  CONSTRAINT act_adjunto_peso_positivo CHECK (peso_bytes > 0),
  CONSTRAINT act_adjunto_peso_no_supera_cuota_completa CHECK (peso_bytes <= 10485760),
  CONSTRAINT act_adjunto_hash_es_sha256_hex CHECK (hash_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT act_adjunto_extension_minuscula CHECK (extension = lower(extension)),
  -- El mismo archivo no se sube dos veces a la misma actividad. Se compara por
  -- contenido (hash), no por nombre: renombrarlo no lo convierte en otro.
  CONSTRAINT act_adjunto_sin_duplicado_por_contenido UNIQUE (id_actividad, hash_sha256)
);
COMMENT ON TABLE ai.act_adjunto IS
  'R19, pestana 2. R11: la cuota de 10 MB es AGREGADA y la impone el disparador de 0009, no un CHECK de fila (P5). R12: se guarda el MIME detectado del contenido real.';
COMMENT ON COLUMN ai.act_adjunto.id_estado_registro IS
  'R14. Relevante para R11: la cuota suma los bytes VIGENTES, asi que dar de baja un adjunto libera su espacio.';

