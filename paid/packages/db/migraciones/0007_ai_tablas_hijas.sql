-- ── 5 · Poblacion Beneficiada ──────────────────────────────────────────────
--
-- ⚠️ ESTA ES LA TABLA QUE EL DISENO AUDITADO DOCUMENTO Y NO IMPLEMENTO (P2).
-- Es la cifra que alimenta el RAO.
--
-- TODO(JACID) Q4/Q10: no se sabe como se desglosa la cifra (¿por sexo? ¿edad?
-- ¿grupo etnico? ¿tipo de servicio recibido?), ni si se registran datos que
-- identifiquen a personas concretas, lo que activaria la Ley 1581 de 2012.
-- Mientras no se sepa, el desglose se apoya en el catalogo `ref.grupo_poblacional`
-- —que se siembra vacio— y NO hay ninguna columna con datos personales: si
-- resultara que hacen falta, se anaden con los controles que esa ley exige, no
-- antes.
CREATE TABLE ai.act_poblacion_beneficiada (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad         bigint NOT NULL REFERENCES ai.actividad(id) ON DELETE CASCADE,
  id_grupo_poblacional smallint NOT NULL REFERENCES ref.grupo_poblacional(id),
  cantidad_personas    integer NOT NULL,
  observacion          text,
  creado_en            timestamptz NOT NULL DEFAULT now(),
  creado_por           bigint,
  modificado_en        timestamptz NOT NULL DEFAULT now(),
  modificado_por       bigint,
  CONSTRAINT act_poblacion_cantidad_positiva CHECK (cantidad_personas > 0),
  CONSTRAINT act_poblacion_unica_por_grupo UNIQUE (id_actividad, id_grupo_poblacional)
);
COMMENT ON TABLE ai.act_poblacion_beneficiada IS
  'R19, pestana 5. LA TABLA QUE P2 PERDIO: es la cifra que alimenta el RAO. Sin datos personales: TODO(JACID) Q10 (Ley 1581 de 2012).';

