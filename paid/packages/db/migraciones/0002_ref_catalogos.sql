-- ═══════════════════════════════════════════════════════════════════════════
-- 0002 — Catalogos de dominio cerrado (esquema `ref`)
--
-- Anti-patron P9: como `VARCHAR` sin catalogo, «BINACIONAL» y «Binacional»
-- cuentan como dos categorias y el consolidado del RAO no cuadra. Todos los
-- dominios cerrados viven aqui.
--
-- ⚠️ TODO(JACID): PROMPT.md habla de «los 26 catalogos de `ref`». Ese numero
-- sale de `anexo_A_ddl_paid.sql`, que no existe. Los catalogos de este archivo
-- son los que las reglas R1–R19 exigen; el recuento no coincide
-- necesariamente. Si el DDL traia catalogos que ninguna regla nombra, aqui
-- faltan. Ver docs/DECISIONES.md, D-13.
--
-- Patron comun de un catalogo:
--   id           clave subrogada
--   codigo       clave natural estable, en MAYUSCULAS_CON_GUION_BAJO. Es la que
--                usan el codigo de la aplicacion y las semillas; el `id` puede
--                cambiar entre despliegues, el `codigo` no.
--   nombre       etiqueta para la interfaz, con tildes y enes
--   descripcion  texto de ayuda, opcional
--   orden        orden de presentacion en los desplegables
--   activo       baja logica de una entrada de catalogo (R14 en miniatura):
--                una entrada retirada debe seguir existiendo, porque hay filas
--                historicas que la referencian
-- ═══════════════════════════════════════════════════════════════════════════


