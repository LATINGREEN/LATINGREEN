-- ── ref.municipio ──
CREATE TABLE ref.municipio (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_departamento  smallint NOT NULL REFERENCES ref.departamento(id),
  codigo_dane      char(5) NOT NULL,
  -- Los dos primeros digitos del codigo DANE de un municipio SON el codigo de
  -- su departamento. Se derivan en una columna generada y se atan al
  -- departamento con una clave foranea: asi es imposible colgar un municipio
  -- del departamento equivocado.
  --
  -- No es desnormalizar (P10): la columna no se digita ni se puede escribir,
  -- se calcula del propio codigo. Lo que estaria prohibido es guardar
  -- `nombre_departamento` repetido por municipio, y eso no ocurre aqui.
  codigo_dane_departamento char(2) GENERATED ALWAYS AS (substring(codigo_dane FROM 1 FOR 2)) STORED,
  nombre           varchar(120) NOT NULL,
  activo           boolean NOT NULL DEFAULT TRUE,
  creado_en        timestamptz NOT NULL DEFAULT now(),
  creado_por       bigint,
  modificado_en    timestamptz NOT NULL DEFAULT now(),
  modificado_por   bigint,
  CONSTRAINT municipio_codigo_dane_unico UNIQUE (codigo_dane),
  CONSTRAINT municipio_codigo_dane_formato CHECK (codigo_dane ~ '^[0-9]{5}$'),
  CONSTRAINT municipio_codigo_coherente_con_departamento
    FOREIGN KEY (codigo_dane_departamento) REFERENCES ref.departamento(codigo_dane)
);
COMMENT ON TABLE ref.municipio IS
  'Division politico-administrativa DANE, nivel municipio. SE SIEMBRA VACIO: la lista oficial (DIVIPOLA) son mas de 1100 filas y se carga del archivo del DANE, no se teclea. Una lista parcial es peor que una vacia porque parece completa.';

