-- ── R10 — El avance de un proyecto: escala de OCHO tramos ──────────────────
--
-- 10, 20, 30, 40, 50, 60, 70, 100. **NO existen 80 ni 90.** El salto del 70 al
-- 100 es deliberado: cada tramo tiene su paquete documental y no hay paquete
-- definido para esos dos.
--
-- PROMPT.md lo senala como el error mas facil de cometer en todo el proyecto:
-- un diseno previo lo cometio «normalizando» la escala a diez tramos. No se
-- completa.
ALTER TABLE ai.proyecto_social
  ADD CONSTRAINT proyecto_social_avance_escala_de_ocho_tramos
  CHECK (porcentaje_avance IS NULL OR porcentaje_avance IN (10,20,30,40,50,60,70,100));

COMMENT ON CONSTRAINT proyecto_social_avance_escala_de_ocho_tramos ON ai.proyecto_social IS
  'R10: 10,20,30,40,50,60,70,100. Los tramos 80 y 90 NO existen en la escala PAID. No completar.';

-- Historico de avances. El manual exige actualizacion mensual.
CREATE TABLE ai.proyecto_avance (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_actividad      bigint NOT NULL REFERENCES ai.proyecto_social(id_actividad) ON DELETE CASCADE,
  porcentaje_avance smallint NOT NULL,
  fecha_avance      date NOT NULL,
  observacion       text NOT NULL,
  id_usuario        bigint REFERENCES seg.usuario(id),
  creado_en         timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT proyecto_avance_escala_de_ocho_tramos
    CHECK (porcentaje_avance IN (10,20,30,40,50,60,70,100)),
  CONSTRAINT proyecto_avance_observacion_no_vacia CHECK (btrim(observacion) <> ''),
  -- Un mismo tramo no se registra dos veces para el mismo proyecto: repetir un
  -- tramo no es avanzar. La progresion (que el tramo nuevo sea mayor que el
  -- ultimo) la impone el disparador de 0009, porque exige comparar con el
  -- historico.
  CONSTRAINT proyecto_avance_tramo_no_repetido UNIQUE (id_actividad, porcentaje_avance)
);
COMMENT ON TABLE ai.proyecto_avance IS
  'R10: cada cambio de avance con fecha, observacion y usuario. El manual exige actualizacion mensual. La progresion la impone el disparador de 0009.';

-- ── R18 — COAMI, relacion cero-a-muchos ────────────────────────────────────
--
-- El manual: «si no hubo participacion NO realice seleccion». La ausencia de
-- filas es un valor legitimo, no un formulario a medio llenar. Por eso es una
-- tabla de relacion y no una columna con valor por defecto.
CREATE TABLE ai.actividad_coami (
  id_actividad bigint NOT NULL REFERENCES ai.actividad(id) ON DELETE CASCADE,
  id_coami     smallint NOT NULL REFERENCES ref.coami(id),
  creado_en    timestamptz NOT NULL DEFAULT now(),
  creado_por   bigint,
  PRIMARY KEY (id_actividad, id_coami)
);
COMMENT ON TABLE ai.actividad_coami IS
  'R18: los siete COAMI de la Reserva Naval, cero-a-muchos. Ninguno por defecto: «si no hubo participacion NO realice seleccion».';

