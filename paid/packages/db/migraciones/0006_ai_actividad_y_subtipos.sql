-- ── Supertipo ──────────────────────────────────────────────────────────────
CREATE TABLE ai.actividad (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tipo_actividad   smallint NOT NULL REFERENCES ref.tipo_actividad(id),

  -- Q1: el algoritmo real no se conoce. Se implementa el patron observado
  -- detras de una interfaz sustituible (GeneradorCodigo, Fase 3), con unicidad
  -- por reintento sobre esta restriccion UNIQUE.
  codigo_actividad    varchar(40) NOT NULL,

  -- La unidad que registra. Es la columna sobre la que RLS decide el ambito
  -- (R6), via la ruta_jerarquica de org.unidad.
  id_unidad           bigint NOT NULL REFERENCES org.unidad(id),

  -- El clavegrama. De aqui parte U1 en la Fase 7: la extraccion propone el
  -- contenido de las once pestanas leyendo este texto, para que el usuario no
  -- vuelva a teclear a mano lo que ya escribio aqui.
  descripcion         text NOT NULL,

  -- A.2.5: fechas sin hora en DATE, no TIMESTAMP. Un TIMESTAMP invita a un
  -- componente horario espurio que desplaza el dia en los informes.
  fecha_inicio        date NOT NULL,
  fecha_fin           date,

  -- R9: la ARC siempre participa. El manual: «siempre se debe poner SI en
  -- ARC». En la interfaz aparece marcado y deshabilitado.
  participo_arc       boolean NOT NULL DEFAULT TRUE,

  -- R19: la obligatoriedad de las once pestanas NO se expresa con NOT NULL
  -- (son tablas hijas que pueden quedar vacias): se calcula aqui, por
  -- disparador (0009), y los consolidados del RAO filtran por esta columna.
  registro_completo   boolean NOT NULL DEFAULT FALSE,

  id_municipio        integer REFERENCES ref.municipio(id),
  id_estado_registro  smallint NOT NULL REFERENCES ref.estado_registro(id),

  -- ═══ R13 — Georreferenciacion ═══════════════════════════════════════════
  --
  -- Va en el SUPERTIPO y no repetida en cada subtipo. R13 exige que jornada,
  -- asistencia, rueda, proyecto y campana capturen los ocho componentes GMS:
  -- son los cinco subtipos, es decir todas las actividades. Declararlo cinco
  -- veces solo crearia cinco oportunidades de que las formulas divergieran.
  -- (El sexto formulario, herramienta AID, no es una actividad y lleva su
  -- propio bloque en ai.herramienta_aid.)
  latitud_grados      smallint NOT NULL,
  latitud_minutos     smallint NOT NULL,
  latitud_segundos    numeric(8,5) NOT NULL,
  latitud_hemisferio  char(1) NOT NULL,
  longitud_grados     smallint NOT NULL,
  longitud_minutos    smallint NOT NULL,
  longitud_segundos   numeric(8,5) NOT NULL,
  longitud_hemisferio char(1) NOT NULL,

  -- Columnas GENERADAS: no se escriben, se derivan (P6). Espejo exacto de
  -- `aDecimal()` en packages/schema/src/coordenadas.ts; una prueba de la
  -- Puerta 1 compara las dos.
  latitud_decimal     numeric(9,6) GENERATED ALWAYS AS (
                        (latitud_grados + latitud_minutos / 60.0 + latitud_segundos / 3600.0)
                        * CASE latitud_hemisferio WHEN 'S' THEN -1 ELSE 1 END
                      ) STORED,
  longitud_decimal    numeric(9,6) GENERATED ALWAYS AS (
                        (longitud_grados + longitud_minutos / 60.0 + longitud_segundos / 3600.0)
                        * CASE longitud_hemisferio WHEN 'W' THEN -1 ELSE 1 END
                      ) STORED,
  ubicacion           geography(Point,4326) GENERATED ALWAYS AS (
                        ST_SetSRID(ST_MakePoint(
                          (((longitud_grados + longitud_minutos / 60.0 + longitud_segundos / 3600.0)
                            * CASE longitud_hemisferio WHEN 'W' THEN -1 ELSE 1 END))::double precision,
                          (((latitud_grados + latitud_minutos / 60.0 + latitud_segundos / 3600.0)
                            * CASE latitud_hemisferio WHEN 'S' THEN -1 ELSE 1 END))::double precision
                        ), 4326)::geography
                      ) STORED,

  CONSTRAINT actividad_latitud_grados_rango CHECK (latitud_grados BETWEEN 0 AND 90),
  CONSTRAINT actividad_latitud_minutos_rango CHECK (latitud_minutos BETWEEN 0 AND 59),
  CONSTRAINT actividad_latitud_segundos_rango CHECK (latitud_segundos >= 0 AND latitud_segundos < 60),
  CONSTRAINT actividad_latitud_hemisferio_valido CHECK (latitud_hemisferio IN ('N', 'S')),
  CONSTRAINT actividad_longitud_grados_rango CHECK (longitud_grados BETWEEN 0 AND 180),
  CONSTRAINT actividad_longitud_minutos_rango CHECK (longitud_minutos BETWEEN 0 AND 59),
  CONSTRAINT actividad_longitud_segundos_rango CHECK (longitud_segundos >= 0 AND longitud_segundos < 60),
  CONSTRAINT actividad_longitud_hemisferio_valido CHECK (longitud_hemisferio IN ('E', 'W')),
  -- P3: las cuatro columnas de auditoria de fila MAS la bitacora de R15.
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          bigint,
  modificado_en       timestamptz NOT NULL DEFAULT now(),
  modificado_por      bigint,

  CONSTRAINT actividad_codigo_unico UNIQUE (codigo_actividad),
  CONSTRAINT actividad_participo_arc_siempre_verdadero CHECK (participo_arc = TRUE),
  CONSTRAINT actividad_fechas_coherentes CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
  CONSTRAINT actividad_descripcion_no_vacia CHECK (btrim(descripcion) <> ''),

  -- Destino de la clave foranea compuesta de cada subtipo. Sin este UNIQUE la
  -- disyuncion de P1 no se puede declarar.
  CONSTRAINT actividad_id_y_tipo_unico UNIQUE (id, id_tipo_actividad)
);

COMMENT ON TABLE ai.actividad IS
  'Supertipo de actividad (P1). Cada subtipo apunta aqui con clave foranea compuesta (id, id_tipo_actividad), lo que hace imposible una actividad con dos subtipos. TODO(JACID): derivado de PROMPT.md.';
COMMENT ON COLUMN ai.actividad.participo_arc IS
  'R9: siempre TRUE. El CHECK lo impone; la interfaz lo muestra marcado y deshabilitado.';
COMMENT ON COLUMN ai.actividad.registro_completo IS
  'R19: calculada por disparador a partir de las once tablas hijas. Los consolidados del RAO filtran por ella.';
COMMENT ON COLUMN ai.actividad.codigo_actividad IS
  'TODO(JACID) Q1: el algoritmo real no se conoce. Patron observado <unidad>R<mes><anio><sufijo de 5>, generado detras de una interfaz sustituible.';
COMMENT ON COLUMN ai.actividad.descripcion IS
  'El clavegrama. Fuente de la extraccion U1 (Fase 7): la IA propone las once pestanas leyendo este texto.';

