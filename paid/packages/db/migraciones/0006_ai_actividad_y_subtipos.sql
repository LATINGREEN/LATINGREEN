-- ═══════════════════════════════════════════════════════════════════════════
-- 0006 — Supertipo de actividad y sus cinco subtipos (esquema `ai`)
--
-- ⚠️ ESTE ARCHIVO ES LA RESPUESTA AL ANTI-PATRON P1.
--
-- Lo prohibido: `tipo_actividad VARCHAR` + `id_referencia_actividad BIGINT`
-- sin clave foranea. Deja huerfanos silenciosos, y un valor mal escrito
-- desvincula filas sin que nada falle.
--
-- Lo implementado: supertipo `ai.actividad` con clave foranea REAL desde cada
-- tabla hija. La disyuncion del subtipo se impone con clave foranea compuesta
-- `(id_actividad, id_tipo_actividad)` y una columna de tipo constante
-- verificada por CHECK. Consecuencias que se pueden comprobar:
--
--   - Una actividad no puede existir sin su subtipo (lo garantiza el
--     disparador de 0009, porque una clave foranea no puede exigir la
--     existencia del lado hijo).
--   - Una actividad no puede tener DOS subtipos distintos: cada tabla hija
--     fija su `id_tipo_actividad` por CHECK, y la clave foranea compuesta
--     obliga a que coincida con el de la actividad. Si la actividad es de tipo
--     1, la fila en `asistencia_humanitaria` (tipo 2) no puede existir.
--
-- Los cinco tipos se insertan AQUI, con identificadores explicitos y fijos, y
-- no en las semillas: los CHECK de las tablas hijas los citan literalmente.
-- Son estructura, no configuracion.
--
-- ⚠️ TODO(JACID): esquema derivado de PROMPT.md. Los campos propios de cada
-- subtipo son minimos a proposito: Q4 (formularios reales) sigue sin
-- responder, y no se inventan campos verosimiles. Ver docs/DECISIONES.md, D-13.
-- ═══════════════════════════════════════════════════════════════════════════

