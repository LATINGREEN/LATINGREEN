-- 0004 — Seguridad (esquema `seg`)
--
-- Cubre R1 (sesion de 10 min), R2 (red cerrada), R3 (captcha de un solo uso),
-- R4 (ocho causas en base, un mensaje en pantalla), R5 (credencial de unidad),
-- R14 (solicitud de eliminacion) y R16 (atribuciones de JACID).
--
-- Anti-patrones que este archivo evita a proposito:
--   P4 — RBAC de verdad: `seg.permiso` con la tripleta modulo/submodulo/accion,
--        `seg.rol_permiso`, `seg.usuario_rol` con vigencia y
--        `seg.rol.id_ambito_visibilidad`. Un campo `id_rol` no es control de
--        acceso basado en roles.
--   P7 — Del testigo de sesion se guarda el RESUMEN, no el testigo. Una lectura
--        de la base no puede equivaler a suplantar una sesion activa.
--
-- ⚠️ TODO(JACID): esquema derivado de PROMPT.md. Ver docs/DECISIONES.md, D-13.
